# -*- coding: utf-8 -*-
"""refusals.py — коды отказа мода RimWorld → человеческий текст для зрителя.

ЗАЧЕМ (найдено постстрим-триажом 2026-09-09). Отказ платного действия в
RimWorld возвращал крустики МОЛЧА: зритель видел уход и возврат денег без
единого слова. Bannerlord и ShedColony в той же ситуации пишут объяснение
(`add_notice_tx`), RimWorld — нет; на эфире 09.09 было два отказа с возвратом
и ноль уведомлений. Ровно ради этого в июле заводили M103: без объяснения
зритель не отличает «я сделал не то» от «у них сломалось» и жмёт снова.

ПОЧЕМУ СЛОВАРЬ НА БЭКЕНДЕ. Та же причина, что у Bannerlord: фронт замерзает на
CDN Twitch до следующего ревью, бэкенд деплоится за минуты. Новый код отказа
появляется вместе с новым действием мода — держи словарь во фронте, и зритель
неделями видел бы сырой код.

КАК ПИСАЛИСЬ ФРАЗЫ. Каждая — по прочитанной ветке мода, а не по имени кода.
Имя обманывает: в Bannerlord 06.09 так появились две фразы, объяснявшие не тот
случай. Здесь набор кодов закрытый и маленький — `CommandQueue.cs` шлёт ровно
три, и все три прочитаны:

  * `no_effect`    — `CommandQueue.cs:419-422`: `command.Execute()` вернул
                     false, то есть игра действие НЕ применила;
  * `queue_full`   — `:87-90`: очередь команд переполнена, заявка вытеснена;
  * `missing_type` — `:383-387`: команда пришла без поля `type` (наш сбой).

Плюс коды, которые ставит сам бэкенд для просроченных заявок.
"""

_EXACT = {
    # Игра не применила действие. Самый частый случай: цель уже в нужном
    # состоянии (полное здоровье, черта уже есть) либо движок отказал молча.
    "no_effect": "Игра не применила это действие — ничего не изменилось. "
                 "Крустики вернулись.",
    # Очередь заявок переполнена: игра не успевает обрабатывать.
    "queue_full": "Игра не успевает обрабатывать заявки — очередь переполнена. "
                  "Крустики вернулись, попробуй чуть позже.",
    # Заявка без типа — это дефект на нашей стороне, а не ошибка зрителя.
    "missing_type": "Сбой на нашей стороне: заявка ушла неполной. "
                    "Крустики вернулись, попробуй ещё раз.",
    # Ставит TTL-сторож бэкенда, когда игра так и не забрала заявку.
    "queued_ttl_expired": "Игра не забрала заявку — похоже, она была закрыта. "
                          "Крустики вернулись.",
    # Действие не объявлено в манифесте модуля — наш недосмотр.
    "action_not_in_manifest": "Это действие сейчас недоступно. "
                              "Крустики вернулись.",
}

# Неизвестный код НЕ показываем сырым и не превращаем в пустоту: зритель
# получает честную общую формулировку, сам код остаётся в логе бэкенда.
_FALLBACK = "Не получилось — игра отказала в этом действии. Крустики вернулись."


def describe(reason: str) -> str:
    """Код отказа → фраза для панели зрителя."""
    code = (reason or "").strip()
    if not code:
        return _FALLBACK
    # Мод иногда добавляет подробность через двоеточие (`code: detail`) —
    # берём голову, детали остаются в логе.
    head = code.split(":", 1)[0].strip().lower()
    return _EXACT.get(head, _FALLBACK)
