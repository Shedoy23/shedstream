import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const path = new URL('../Расширение/frontend/viewer-usage.js', import.meta.url);
assert.ok(fs.existsSync(path), 'Missing bounded semantic UI usage collector');
const requests = [];
const timers = new Map();
let timerId = 0;
let now = 1000;
let fail = false;
const listeners = {};
const context = vm.createContext({console, Date: {now: () => now}, crypto: {randomUUID: () => `00000000-0000-4000-8000-${String(++timerId).padStart(12,'0')}`}, setTimeout(fn) {timers.set(++timerId, fn); return timerId;}, clearTimeout(id) {timers.delete(id);}, document: {hidden:false, addEventListener(name, fn){listeners[name] = fn;}}, location: {pathname:'/extension.html'}, fetch: async (url, options) => {requests.push({url, ...options}); if (fail) throw Error('offline'); return {ok:true, status:200};}});
vm.runInContext("window = globalThis; const API_URL = 'https://example.invalid'; let authToken = 'token-a';", context);
vm.runInContext(fs.readFileSync(path, 'utf8'), context);
const usage = context.ShedLink.usage;
assert.ok(usage);
await usage.flush();
assert.equal(requests.length, 0, 'No automatic polling/page rendering counted as use');
usage.trackPanel('bannerlord');
usage.trackPanel('bannerlord');
usage.trackSection('bannerlord:skills');
usage.trackSection('bannerlord:skills');
usage.trackAction('bannerlord:hero.set_class');
await usage.flush();
let body = JSON.parse(requests[0].body);
assert.deepEqual(body.events.map(x => [x.kind,x.feature,x.count]), [['panel_view','bannerlord:panel',1], ['section_open','bannerlord:skills',2], ['action_attempt','bannerlord:hero.set_class',1]]);
assert.equal(requests[0].headers['X-Twitch-JWT'], 'token-a');
assert.ok(!/username|payload|login|client_action_id/.test(requests[0].body), 'No private action contents');
fail = true;
usage.trackAction('bannerlord:hero.set_class');
await usage.flush();
const retried = requests.at(-1).body;
fail = false;
await usage.flush();
assert.equal(requests.at(-1).body, retried, 'Retry must reuse exact body/dedupe ID');
usage.trackSection('bannerlord:skills');
vm.runInContext("authToken = 'token-b'", context);
await usage.flush();
assert.equal(requests.at(-1).body, retried, 'Queued old auth context must never be attributed to new identity/channel');
for (let i=0;i<1000;i++) usage.trackSection('bannerlord:skills');
await usage.flush();
body = JSON.parse(requests.at(-1).body);
assert.ok(body.events.reduce((n,e)=>n+e.count,0)<=100);
assert.ok(body.events.length<=20);
assert.ok(body.events.every(e=>e.count<=20));
const before = requests.length;
usage.trackAction('private user text');
await usage.flush();
assert.equal(requests.length, before, 'Invalid feature strings must not leave the client');
console.log('PASS: explicit hooks only, aggregate counts, bounded batches, retry dedupe, auth-bound queue, no private payload');
