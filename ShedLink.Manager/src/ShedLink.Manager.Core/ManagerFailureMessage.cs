using System.Net;
using ShedLink.Manager.Core.Api;

namespace ShedLink.Manager.Core;

/// <summary>
/// Превращает сбой в то, что можно показать человеку: что случилось и что
/// делать дальше.
///
/// ЗАЧЕМ ЭТО В CORE, А НЕ В ОКНЕ. Критерий M1 (`ROADMAP.md`, матрица R3) звучит
/// так: каждая ошибка из матрицы объясняется понятным сообщением и следующим
/// рекомендуемым действием. Пока текст жил приватным методом окна, проверить
/// это можно было только глазами — а незнакомый тестировщик упирается в текст
/// раньше, чем в любую другую часть продукта.
/// </summary>
public static class ManagerFailureMessage
{
    /// <summary>Текст, который увидит человек. Всегда с продолжением.</summary>
    public static string For(Exception exception) => exception switch
    {
        // Отказ Windows в правах. До 2026-08-16 этот случай не ловил НИКТО:
        // фильтры обработчиков перечисляли IOException, а
        // UnauthorizedAccessException наследуется от SystemException и под них
        // не подходит, поэтому установка в защищённую папку роняла приложение.
        UnauthorizedAccessException =>
            "Windows не дал записать в папку игры. Закрой игру, затем запусти "
            + "Manager от имени администратора или перенеси игру из защищённой "
            + "папки и повтори установку.",

        // Диск, занятый файл, оборванная запись. Установка транзакционная,
        // поэтому прежняя версия уже на месте — это важно сказать прямо.
        IOException =>
            "Не удалось записать файлы: обычно это запущенная игра или "
            + "нехватка места на диске. Закрой игру, освободи место и повтори "
            + "установку — прежняя версия осталась на месте.",

        // Не совпали размер, SHA-256, подпись или журнал установки.
        InvalidDataException =>
            "Файлы не прошли проверку целостности, установка отменена и "
            + "прежняя версия на месте. Повтори попытку; если повторится — "
            + "собери диагностический отчёт и пришли его разработчику.",

        ManagerApiException api when api.ErrorCode == "manager_auth_unavailable" =>
            "Manager API пока не включён на сервере. Это не твоя ошибка — "
            + "напиши разработчику.",

        ManagerApiException api when api.StatusCode == HttpStatusCode.Unauthorized
                                 || api.StatusCode == HttpStatusCode.Forbidden =>
            "Сервер не принял ключ интеграции: он мог быть отозван или "
            + $"просрочен ({api.ErrorCode}). Войди заново, затем смени ключ "
            + "кнопкой «Сменить ключ».",

        ManagerApiException api =>
            $"Сервер отклонил запрос ({api.ErrorCode}). Повтори через минуту; "
            + "если повторится — собери диагностический отчёт и пришли его "
            + "разработчику.",

        TaskCanceledException =>
            "Сервер не ответил вовремя. Проверь интернет и повтори.",

        HttpRequestException =>
            "Не удалось связаться с ShedLink backend. Проверь интернет и "
            + "повтори; если интернет в порядке, сервер сейчас недоступен — "
            + "попробуй позже.",

        // Сюда попадают наши собственные проверки состояния («игра запущена»,
        // «сначала найди игру»): их текст уже написан для человека.
        InvalidOperationException invalid => invalid.Message,

        _ => "Неожиданная ошибка Manager. Собери диагностический отчёт и "
            + "пришли его разработчику.",
    };

    /// <summary>
    /// Сбой, который обработчик обязан поймать сам, а не ронять приложение.
    /// Держится рядом с текстами намеренно: список типов и список сообщений
    /// разъезжаются молча, и разъехались уже один раз.
    /// </summary>
    public static bool IsExpected(Exception exception) =>
        exception is ManagerApiException
                  or HttpRequestException
                  or TaskCanceledException
                  or InvalidOperationException
                  or InvalidDataException
                  or IOException
                  or UnauthorizedAccessException;
}
