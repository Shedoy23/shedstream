        /// <summary>Выбор варианта из n; тесты подменяют на детерминированный.</summary>
        internal static Func<int, int> Pick = n => Rng.Next(n);
        internal static TimeSpan Repeat = TimeSpan.FromSeconds(45);
        private static readonly Random Rng = new Random();
        private static readonly Dictionary<string, int> LastVariant = new Dictionary<string, int>();
        private static readonly Dictionary<string, DateTime> LastSaid = new Dictionary<string, DateTime>();
        private static readonly object Gate = new object();

        internal static void Reset() { lock (Gate) { LastVariant.Clear(); LastSaid.Clear(); } }

        /// <summary>Сказать реплику события kind. key — что именно (цель, крепость): тот же
        /// kind с тем же key не повторяем чаще Repeat.</summary>
        internal static void Say(string kind, string key, params object[] args)
        {
            try
            {
                string line;
                lock (Gate)
                {
                    if (!Table.TryGetValue(kind, out string[] variants) || variants.Length == 0) return;
                    string said = kind + "|" + key;
                    DateTime now = DateTime.UtcNow;
                    if (LastSaid.TryGetValue(said, out DateTime at) && now - at < Repeat) return;
                    LastSaid[said] = now;
                    int pick = Pick(variants.Length);
                    if (variants.Length > 1 && LastVariant.TryGetValue(kind, out int last) && last == pick)
                        pick = (pick + 1) % variants.Length;
                    LastVariant[kind] = pick;
                    line = string.Format(variants[pick], args);
                }
                StreamStatus.Note(line);
            }
            catch (Exception)
            {
                // Экран стрима не должен ронять автопилот.
            }
        }
