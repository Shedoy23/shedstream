# Наша поломка, а не правило игры. Сюда же уезжает всё, что оканчивается на
# _failed / _crash / _crashed / _threw / _null / _blocked / _not_set —
# это внутренние сбои мода, и зрителю про них честно говорим одинаково.
_OUR_FAULT_SUFFIXES = (
    "_failed", "_crash", "_crashed", "_threw", "_null", "_blocked",
    "_not_set", "_missing", "_object",
)
_OUR_FAULT_EXACT = {
    "crashed", "exception", "engine_create_clan_null", "behavior_missing",
    "spawn_failed", "create_failed", "create_threw", "create_returned_null",
    "body_field_not_found",
}
_OUR_FAULT_TEXT = ("Не получилось — сбой на стороне игры. "
                   "Это наша проблема, не твоя.")

# Когда кода нет ни в одном списке. Честнее пустого места: зритель хотя бы
# знает, что отказ настоящий, а не «нажалось мимо».
_FALLBACK = "Игра отказала в этом действии."


def describe(reason: str) -> str:
    """Код отказа → фраза для панели зрителя.

    Неизвестный код НЕ превращается в пустоту и не показывается сырым:
    зритель получает общую честную формулировку, а сам код остаётся в логе.
    """
    code = (reason or "").strip()
    if not code:
        return _FALLBACK
    head = code.split(":", 1)[0].strip().lower()

    if head in _EXACT:
        return _EXACT[head]
    if head in _OUR_FAULT_EXACT:
        return _OUR_FAULT_TEXT
    for prefix, text in _PREFIXES:
        if head.startswith(prefix):
            return text
    if any(head.endswith(suf) for suf in _OUR_FAULT_SUFFIXES):
        return _OUR_FAULT_TEXT
    return _FALLBACK
